def materials() -> str:
    out = HEADER + ".. _gui-ref-materials:\n\n" + _title("Built-in material library", "=")
    data = json.loads(library.BUILTIN.read_text(encoding="utf-8"))
    out += _esc(data.get("description", "")) + "\n\n"
    props = list(M.PROPERTIES)
    head = ["Material", "Category"] + [f"{p} ({M.PROPERTIES[p][1]})" for p in props]
    rows = [[_esc(mat["name"]), _esc(mat.get("category", ""))]
            + [f"{mat['properties'][p]:.4g}" if p in mat.get("properties", {}) else "" for p in props]
            for mat in data["materials"]]
    out += _table(head, rows)
    out += "Properties: " + "; ".join(f"{_lit(p)}: {_esc(lab)}" for p, (lab, _) in M.PROPERTIES.items()) \
        + ".\n\n"
    return out


