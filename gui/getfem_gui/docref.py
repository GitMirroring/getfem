# ------------------------------------------------------------------ rst helpers

def _esc(text) -> str:
    """Plain text for reStructuredText (no markup)."""
    s = str(text)
    for c in ("\\", "*", "`", "|", "_"):
        s = s.replace(c, "\\" + c)
    return s


def _lit(value) -> str:
    return "``" + (json.dumps(value) if not isinstance(value, str) else value) + "``"


def _title(text: str, char: str, over: bool = False) -> str:
    line = char * max(len(text), 8)     # (7 "=" would look like a conflict marker to git)
    return (line + "\n" if over else "") + text + "\n" + line + "\n\n"


def _table(header: list[str], rows: list[list[str]], widths: list[int] | None = None) -> str:
    if not rows:
        return ""
    out = [".. list-table::", "   :header-rows: 1"]
    if widths:
        out.append("   :widths: " + " ".join(map(str, widths)))
    out.append("")
    for row in [header] + rows:
        for i, cell in enumerate(row):
            lines = (cell.strip() or "").split("\n")
            out.append((("   * - " if i == 0 else "     - ") + lines[0]).rstrip())
            out += ["       " + x for x in lines[1:]]
    return "\n".join(out) + "\n\n"


def _key(f: E.Field, base: tuple) -> str:
    rel = f.key[len(base):] if f.key[:len(base)] == base else f.key
    return ".".join(str(x) for x in rel) or "(the node)"


def _describe(f: E.Field) -> str:
    if f.kind == "choice":
        what = ", ".join(_lit(v) + (f" ({_esc(lab)})" if str(lab) != str(v) else "")
                         for v, lab in f.choices)
        text = "one of " + what if what else "a name"
    else:
        text = KINDS.get(f.kind, f.kind)
    hlp = "\n".join(x for x in f.help.split("\n") if x != E.VECTOR_TIP)
    return text + (". " + _esc(hlp) if hlp else "")


def _fields_doc(model: dict, path: tuple, base: tuple | None = None, skip=()) -> str:
    """The table of the fields of a node, then its notes."""
    base = path if base is None else base
    rows, notes = [], []
    for f in E.fields(model, path):
        if f.kind == "info":
            notes += [x for x in f.help.split("\n") if x and not x.startswith(("No ", "Edges:", "Faces:",
                                                                                "Regions (in"))]
            continue
        if _key(f, base) in skip or (f.key[:len(base)] != base and f.key[:len(path)] != path):
            continue
        rows.append([_esc(f.label) if f.label else "", _lit(_key(f, base)), _describe(f)])
    out = _table(["Field", "Key", "Value"], rows, [20, 20, 60])
    for n in notes:
        out += _esc(n) + "\n\n"
    return out


def _model_with_source(src: dict) -> dict:
    m = M.default_model()
    m["geometries"][0]["source"] = copy.deepcopy(src)
    m["geometries"][0]["selections"] = {}
    return m


