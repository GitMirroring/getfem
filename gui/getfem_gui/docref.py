"""Reference pages of the user documentation, generated from the code.

The forms of the interface, the meshers, the selection criteria, the
modules, the material library, the export formats and the command line are
described by tables of this package: the reference pages are written from
them, so that they follow the code. ``tests/test_doc.py`` checks that the
pages in the documentation are up to date.

    python -m getfem_gui.docref [directory]

writes them (by default into doc/sphinx/source/gui/reference of the
GetFEM sources).
"""

