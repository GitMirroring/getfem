def command_line() -> str:
    out = HEADER + ".. _gui-ref-cli:\n\n" + _title("Command line", "=")
    out += "``python -m getfem_gui COMMAND ...``, run from the ``gui`` directory.\n\n"
    p = cli.parser()
    sub = next(a for a in p._actions if a.__class__.__name__ == "_SubParsersAction")
    helps = {a.dest: a.help for a in sub._choices_actions}
    for name, sp in sub.choices.items():
        out += _title(name, "-") + _esc(helps.get(name, "")).capitalize() + ".\n\n"
        out += ".. code-block:: text\n\n" + "\n".join(
            "   " + line for line in sp.format_usage().replace("usage: ", "").strip().split("\n")) + "\n\n"
        rows = []
        for a in sp._actions:
            if a.dest == "help":
                continue
            names = ", ".join(a.option_strings) or a.dest
            rows.append([_lit(names), _esc(a.help or ("the model file" if a.dest == "model" else ""))])
        out += _table(["Argument", "Meaning"], rows, [30, 70])
    return out


def examples() -> str:
    out = HEADER
    rows = []
    for f in sorted(EXAMPLES.glob("*.json")):
        m = M.load(f)
        geoms = ", ".join(sorted({(g.get("source", {}).get("type", "?") +
                                   (f" {g['source'].get('dim')}D" if g.get("source", {}).get("dim") else ""))
                                  for g in m.get("geometries", [])}))
        meshers_ = ", ".join(sorted({x.get("mesher", "?") for x in m.get("meshes", [])}))
        mods = ", ".join(sorted({mod.get("type") for md in m.get("models", []) for mod in md.get("modules", [])}))
        rows.append([f":ref:`{f.name} <gui-example-{f.stem}>`", _esc(m.get("name", "")), geoms,
                     meshers_, mods])
    out += _table(["File", "Name", "Geometries", "Meshers", "Modules"], rows)
    return out


PAGES = {
    "geometry_sources.rst": geometry_sources,
    "shapes.rst": shapes,
    "selections.rst": selections,
    "meshers.rst": meshers,
    "modules.rst": modules,
    "model_nodes.rst": model_nodes,
    "materials.rst": materials,
    "export_formats.rst": export_formats,
    "command_line.rst": command_line,
    "examples_table.inc": examples,
}


def pages() -> dict[str, str]:
    return {name: fn().rstrip("\n") + "\n" for name, fn in PAGES.items()}


def write(directory: str | Path = DEFAULT_DIR) -> list[Path]:
    d = Path(directory)
    d.mkdir(parents=True, exist_ok=True)
    out = []
    for name, text in pages().items():
        p = d / name
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
            out.append(p)
    return out


if __name__ == "__main__":
    for p in write(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DIR):
        print("written:", p)
